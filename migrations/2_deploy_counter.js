// migrations/2_deploy_counter.js  (BONUS: second contract)
const fs = require("fs");
const path = require("path");
const VisitCounter = artifacts.require("VisitCounter");

module.exports = async function (deployer) {
  await deployer.deploy(VisitCounter);
  const instance = await VisitCounter.deployed();
  console.log("\nVisitCounter deployed at:", instance.address);

  // Add to the file written by migration 1
  // `truffle test` re-runs migrations; do not overwrite the frontend file with temporary test addresses
  if (process.argv.includes("test")) return;

  const file = path.join(__dirname, "..", "src", "contract-info.js");
  const old = fs.readFileSync(file, "utf8");
  const info = JSON.parse(old.substring(old.indexOf("{"), old.lastIndexOf("}") + 1));
  info.visitCounter = { address: instance.address, abi: VisitCounter.abi };

  fs.writeFileSync(file, "// Auto-generated by `truffle migrate`. Do not edit by hand.\nwindow.CONTRACT_INFO = " +
    JSON.stringify(info, null, 2) + ";\n");
  console.log("Updated src/contract-info.js");
};

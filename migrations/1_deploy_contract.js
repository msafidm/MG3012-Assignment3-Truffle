// migrations/1_deploy_contract.js
// Deploys FeedbackBoard (contracts/SmartContract.sol) to the network chosen with `truffle migrate`.
// It also saves the deployed address + ABI into src/contract-info.js so the frontend can use them automatically.

const fs = require("fs");
const path = require("path");
const FeedbackBoard = artifacts.require("FeedbackBoard");

module.exports = async function (deployer, network, accounts) {
  await deployer.deploy(FeedbackBoard);
  const instance = await FeedbackBoard.deployed();
  const chainId = await web3.eth.getChainId();

  console.log("\nFeedbackBoard deployed at:", instance.address);
  console.log("Deployer (owner):", accounts[0]);

  // `truffle test` re-runs migrations; do not overwrite the frontend file with temporary test addresses
  if (process.argv.includes("test")) return;

  const file = path.join(__dirname, "..", "src", "contract-info.js");
  const info = { chainId: Number(chainId), network: network,
                 feedbackBoard: { address: instance.address, abi: FeedbackBoard.abi } };

  fs.writeFileSync(file, "// Auto-generated by `truffle migrate`. Do not edit by hand.\nwindow.CONTRACT_INFO = " +
    JSON.stringify(info, null, 2) + ";\n");
  console.log("Saved address and ABI to src/contract-info.js");
};
